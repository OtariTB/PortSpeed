def build_and_compile(out_dir: Path | None = None) -> tuple[Path, Path]:
    if out_dir is None:
        local_app = os.environ.get("LOCALAPPDATA", "")
        if local_app:
            out_dir = Path(local_app) / "NFSProStreetResearch" / "phase3" / "recomp"
        else:
            out_dir = WORKSPACE / "gen"
    out_dir.mkdir(parents=True, exist_ok=True)

    as_path = out_dir / "ctor_callback.ts"
    wasm_path = out_dir / "ctor_callback.wasm"

    as_path.write_text(AS_HEADER, encoding="utf-8")

    asc_cmd = WORKSPACE / "web" / "node_modules" / ".bin" / ("asc.cmd" if os.name == "nt" else "asc")
    if not asc_cmd.is_file():
        raise FileNotFoundError(f"AssemblyScript compiler not found at {asc_cmd}")

    cmd = [
        str(asc_cmd),
        str(as_path),
        "--target", "release",
        "--outFile", str(wasm_path),
        "--runtime", "stub",
        "--use", "abort=",
        "--memoryBase", "0x00010000",
        "--initialMemory", "256",
        "--maximumMemory", "1024",
    ]

    res = subprocess.run(cmd, capture_output=True, text=True, check=False)
    if res.returncode != 0:
        print("asc stdout:\n", res.stdout)
        print("asc stderr:\n", res.stderr)
        raise RuntimeError(f"asc compilation failed with code {res.returncode}")

    return as_path, wasm_path


def main():
    as_path, wasm_path = build_and_compile()
    print(f"Generated AssemblyScript: {as_path}")
    print(f"Compiled WebAssembly:     {wasm_path} ({wasm_path.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
